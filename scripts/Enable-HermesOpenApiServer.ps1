function Ensure-FirewallRule {
  param(
    [int]$Port,
    [string]$RemoteAddress
  )
  if ($NoFirewall) {
    return
  }
  $displayName = "SoftwareDoc Hermes OpenAI API Server $Port"
  $existing = Get-NetFirewallRule -DisplayName $displayName -ErrorAction SilentlyContinue
  if ($existing) {
    Remove-NetFirewallRule -DisplayName $displayName
  }
  $remote = if ($RemoteAddress -and $RemoteAddress -ne "Any") { $RemoteAddress } else { "Any" }
  New-NetFirewallRule `
    -DisplayName $displayName `
    -Direction Inbound `
    -Action Allow `
    -Protocol TCP `
    -LocalPort $Port `
    -RemoteAddress $remote | Out-Null
}

function Ensure-PortProxy {
  param(
    [int]$PublicPort,
    [int]$InternalPort
  )
  Start-Service iphlpsvc -ErrorAction SilentlyContinue
  netsh interface portproxy delete v4tov4 listenaddress=0.0.0.0 listenport=$PublicPort *> $null
  netsh interface portproxy delete v4tov4 listenaddress=127.0.0.1 listenport=$PublicPort *> $null
  netsh interface portproxy add v4tov4 listenaddress=0.0.0.0 listenport=$PublicPort connectaddress=127.0.0.1 connectport=$InternalPort | Out-Null
}

function Register-OpenApiTask {
  param(
    [string]$Name,
    [string]$RunnerPath,
    [string]$Root
  )
  if ($NoScheduledTask) {
    return
  }
  $existing = Get-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
  if ($existing) {
    Stop-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
    Start-Sleep -Seconds 2
  }
  $arguments = @(
    "-NoProfile",
    "-ExecutionPolicy", "Bypass",
    "-File", "`"$RunnerPath`"",
    "-InstallDir", "`"$Root`""
  ) -join " "
  $action = New-ScheduledTaskAction -Execute "powershell.exe" -Argument $arguments -WorkingDirectory $Root
  $trigger = New-ScheduledTaskTrigger -AtLogOn
  $principal = New-ScheduledTaskPrincipal `
    -UserId ([Security.Principal.WindowsIdentity]::GetCurrent().Name) `
    -LogonType Interactive `
    -RunLevel Highest
  $settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -RestartCount 3 `
    -RestartInterval (New-TimeSpan -Minutes 1)
  Register-ScheduledTask -TaskName $Name -Action $action -Trigger $trigger -Principal $principal -Settings $settings -Force | Out-Null
  Start-ScheduledTask -TaskName $Name
}

function Wait-ApiServer {
  param(
    [int]$Port,
    [string]$BearerToken
  )
  $healthUri = "http://127.0.0.1:$Port/health"
  $modelsUri = "http://127.0.0.1:$Port/v1/models"
  $headers = @{}
  if ($BearerToken) {
    $headers.Authorization = "Bearer $BearerToken"
  }
  for ($i = 0; $i -lt 30; $i++) {
    try {
      Invoke-RestMethod -Uri $healthUri -TimeoutSec 3 | Out-Null
      if ($headers.Count) {
        Invoke-RestMethod -Uri $modelsUri -Headers $headers -TimeoutSec 3 | Out-Null
      } else {
        Invoke-RestMethod -Uri $modelsUri -TimeoutSec 3 | Out-Null
      }
      return
    } catch {
      Start-Sleep -Seconds 2
    }
  }
  throw "Hermes API Server did not become healthy on port $Port. Check $InstallDir\logs\hermes-openapi-*.log."
}

