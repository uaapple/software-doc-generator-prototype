function Assert-Administrator {
  $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
  $principal = [Security.Principal.WindowsPrincipal]::new($identity)
  if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw "Please run this script from an elevated PowerShell window."
  }
}

function Import-EnvFile {
  param(
    [string]$Path,
    [switch]$Required
  )
  if (-not (Test-Path -LiteralPath $Path)) {
    if ($Required) {
      throw "Environment file not found: $Path"
    }
    return
  }
  foreach ($line in Get-Content -LiteralPath $Path -Encoding UTF8) {
    $trimmed = $line.Trim()
    if (-not $trimmed -or $trimmed.StartsWith("#")) {
      continue
    }
    $index = $trimmed.IndexOf("=")
    if ($index -le 0) {
      continue
    }
    $key = $trimmed.Substring(0, $index).Trim()
    $value = $trimmed.Substring($index + 1).Trim().Trim('"').Trim("'")
    [Environment]::SetEnvironmentVariable($key, $value, "Process")
  }
}

function Write-EnvFile {
  param(
    [string]$Path,
    [hashtable]$Values
  )
  $lines = @(
    "# Hermes OpenAI-compatible API Server environment",
    "# Generated by Enable-HermesOpenApiServer.ps1"
  )
  foreach ($key in ($Values.Keys | Sort-Object)) {
    $value = [string]$Values[$key]
    $lines += "$key=$value"
  }
  $parent = Split-Path -Parent $Path
  New-Item -ItemType Directory -Force -Path $parent | Out-Null
  $lines | Set-Content -LiteralPath $Path -Encoding UTF8
}

function Get-RandomApiKey {
  $bytes = New-Object byte[] 32
  $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
  try {
    $rng.GetBytes($bytes)
  } finally {
    $rng.Dispose()
  }
  return "hsk_" + [Convert]::ToBase64String($bytes).Replace("+", "-").Replace("/", "_").TrimEnd("=")
}

function Resolve-HermesCommand {
  param([string]$Root)
  $candidates = @()
  if ($env:HERMES_COMMAND) {
    $candidates += $env:HERMES_COMMAND
  }
  $candidates += @(
    (Join-Path $Root "runtime\hermes-agent\hermes.cmd"),
    (Join-Path $Root "runtime\hermes\hermes.cmd"),
    (Join-Path $Root "hermes.cmd")
  )
  foreach ($candidate in $candidates) {
    if ($candidate -and (Test-Path -LiteralPath $candidate)) {
      return (Resolve-Path -LiteralPath $candidate).Path
    }
  }
  throw "Hermes command not found. Check HERMES_COMMAND in $Root\software-doc-worker.env."
}

function Resolve-HermesHome {
  param(
    [string]$Root,
    [string]$HermesCommand
  )
  if ($env:HERMES_HOME) {
    return $env:HERMES_HOME
  }
  $homeFromCmd = $null
  if ($HermesCommand.EndsWith(".cmd", [StringComparison]::OrdinalIgnoreCase)) {
    foreach ($line in Get-Content -LiteralPath $HermesCommand -Encoding ASCII) {
      if ($line -match '^\s*set\s+HERMES_HOME=(.+?)\s*$') {
        $homeFromCmd = $Matches[1].Trim('"')
        break
      }
    }
  }
  if ($homeFromCmd) {
    return $homeFromCmd
  }
  return (Join-Path $Root "runtime\hermes-home")
}

function Resolve-HermesPython {
  param([string]$HermesCommand)
  $hermesRoot = Split-Path -Parent $HermesCommand
  $candidates = @(
    (Join-Path $hermesRoot "python\python.exe"),
    (Join-Path $hermesRoot "venv\Scripts\python.exe")
  )
  foreach ($candidate in $candidates) {
    if (Test-Path -LiteralPath $candidate) {
      return (Resolve-Path -LiteralPath $candidate).Path
    }
  }
  throw "Cannot locate Hermes Python runtime under $hermesRoot."
}

function Ensure-Pip {
  param([string]$PythonExe)
  & $PythonExe -m pip --version *> $null
  if ($LASTEXITCODE -eq 0) {
    return
  }

  $getPip = Join-Path ([IO.Path]::GetTempPath()) ("get-pip-" + [guid]::NewGuid().ToString("N") + ".py")
  Write-Host "pip not found in Hermes Python runtime; downloading get-pip.py..."
  Invoke-WebRequest -Uri "https://bootstrap.pypa.io/get-pip.py" -OutFile $getPip
  try {
    & $PythonExe $getPip --no-warn-script-location
    if ($LASTEXITCODE -ne 0) {
      throw "get-pip.py failed with exit code $LASTEXITCODE"
    }
  } finally {
    Remove-Item -LiteralPath $getPip -Force -ErrorAction SilentlyContinue
  }
}

function Ensure-PythonPackage {
  param(
    [string]$PythonExe,
    [string]$ImportName,
    [string]$PackageName
  )
  & $PythonExe -c "import $ImportName" *> $null
  if ($LASTEXITCODE -eq 0) {
    Write-Host "Python package already available: $ImportName"
    return
  }
  Write-Host "Installing Python package: $PackageName"
  & $PythonExe -m pip install --disable-pip-version-check --upgrade $PackageName
  if ($LASTEXITCODE -ne 0) {
    throw "Failed to install Python package: $PackageName"
  }
}

